#!/usr/bin/env python3
"""Turn splat's linker script into a linker command file for MWLDPS2.

The linker needs a file that tells it what goes where. GNU ld calls that a
linker script (.ld), and splat writes one for every module. MWLDPS2, the
linker the game was originally built with, reads its own kind instead, called
a linker command file (.lcf). This script translates one into the other.

Splat still decides the layout. I only translate the few kinds of line it
writes, and skip its bookkeeping, which nothing in the game uses. If I find a
line I don't recognise, I stop instead of guessing.

Each module is one continuous block, apart from anything that comes before
its first fixed address (the main program's ELF header), which gets a block of
its own at address 0. I worked out the command file format by trying things
with MWLDPS2 itself, and the comments below say what I found.
"""

import argparse
from collections import Counter
from dataclasses import dataclass, field
from itertools import takewhile
import json
from pathlib import Path

from tools.so3 import ROOT
from tools.so3.formats import require

# The modules that link with MWLDPS2 instead of GNU ld. I'm moving them over
# one at a time.
LINKER_CONFIG = ROOT / 'config/manifests/linker.json'

# MWLDPS2 starts a program at __start unless it's told otherwise. An overlay
# doesn't have a real entry point, so I put it at the overlay's first byte.
ENTRY_SYMBOL = '__start'
# The command file's single memory region, and the single output section in
# it. They're only names; neither ends up in the image.
MEMORY_REGION = 'module'
OUTPUT_SECTION = '.module'

# The C++ compiler's exception tables. In the original they aren't in the
# overlays at all. They're in the main program, in one exception index for the
# whole game. MWLDPS2 insists on placing them, though, so they go in a region
# of their own, and only the module's region becomes the image. 0x10000000 is
# far outside the PS2's 32 MiB of memory, so it can't overlap anything real.
EXCEPTION_SECTIONS = ('.exceptix', '.exception')
ELSEWHERE_REGION = 'elsewhere'
ELSEWHERE_OUTPUT_SECTION = '.elsewhere'
ELSEWHERE_ADDRESS = 0x10000000

# The main program's ELF header comes first in its file but sits at address 0,
# far below its code. Sections that come before the first fixed address go in
# a region of their own starting at 0, the way GNU ld's position starts at 0.
FILE_START_REGION = 'file_start'
FILE_START_OUTPUT_SECTION = '.file_start'
INDENT = ' ' * 8
HEADER_COMMENT = "# Generated by tools/so3/build/lcf.py from splat's linker script."

# Lines that only give the script its shape.
STRUCTURE_LINES = ('', 'SECTIONS', '{')
BLOCK_END = '}'
# splat ends its script by throwing away every section it didn't place.
# MWLDPS2 leaves out sections that aren't placed by itself, so this block has
# no equivalent.
DISCARD_BLOCK = '/DISCARD/ :'
DISCARD_EVERYTHING = '*(*);'
# splat's bookkeeping, which nothing in the game refers to: it tracks the
# position in the file (__romPos) and gives each section start and end symbols.
BOOKKEEPING_STARTS = ('HIDDEN(__romPos = ', '__romPos += SIZEOF(', '__romPos = ALIGN(__romPos, ',
                      # Gaps are filled with zeros, which MWLDPS2 does anyway.
                      'FILL(0x00000000)')
# The right-hand sides splat uses for its section start and end symbols.
BOOKKEEPING_VALUES = ('.', '__romPos')
BOOKKEEPING_FUNCTIONS = ('ADDR(', 'ABSOLUTE(')


@dataclass
class Placement:
    """Put one object's section here, like `code.c.o (.text)`."""
    path: Path
    section: str

    def command(self):
        # MWLDPS2 names objects by file name only. A path is a syntax error.
        return f'{self.path.name} ({self.section})'


@dataclass
class Alignment:
    """Move forward to the next multiple of `boundary`."""
    boundary: int

    def command(self):
        return f'. = ALIGN(0x{self.boundary:X});'


@dataclass
class Padding:
    """Leave `size` bytes of zeros."""
    size: int

    def command(self):
        # MWLDPS2 doesn't understand `+=`.
        return f'. = . + 0x{self.size:X};'


@dataclass
class SplatSection:
    """One section block of splat's script, and what goes in it, in order.

    `address` is only set when splat gives the section a fixed address.
    `noload` marks a section that takes up memory but not file space, like
    .bss. `subalign` is GNU's "align every piece in this section to n bytes".
    """
    name: str
    address: int | None
    noload: bool
    subalign: int | None
    contents: list = field(default_factory=list)

    def commands(self):
        """The command file lines for this section."""
        lines = []
        if self.address is not None:
            lines.append(f'. = 0x{self.address:X};')
        if self.subalign is not None:
            # ALIGNALL is the closest match. It only ever raises alignment,
            # though, while SUBALIGN can lower it too.
            lines.append(f'ALIGNALL({self.subalign});')
        lines += [item.command() for item in self.contents]
        return lines


def inside(line, start, end):
    """The text between `start` and `end` if the line is exactly that, otherwise None."""
    if line.startswith(start) and line.endswith(end) and len(line) >= len(start) + len(end):
        return line[len(start):len(line) - len(end)]
    return None


def is_name(text):
    """Whether the text is a section or symbol name: letters, digits, dots and underscores."""
    return bool(text) and all(character.isalnum() or character in '._' for character in text)


def hex_number(text):
    """Read `0x...`, or None if the text isn't a hex number."""
    if text and text.startswith('0x'):
        try:
            return int(text, 16)
        except ValueError:
            return None
    return None


def parse_section_header(line):
    """Read a section header, like `.text 0x3483C0 : AT(text_ROM_START) SUBALIGN(16)`.

    The name comes first, then an optional fixed address and an optional
    (NOLOAD), then a colon. After the colon, AT() says where the section goes
    in the file, which follows from the order anyway, and SUBALIGN() gives the
    alignment for everything in it.
    """
    before, colon, after = line.partition(' :')
    words = before.split()
    if not colon or not words or not words[0].startswith('.') or not is_name(words[0]):
        return None
    section = SplatSection(name=words[0], address=None, noload=False, subalign=None)
    for word in words[1:]:
        if word == '(NOLOAD)':
            section.noload = True
        elif (address := hex_number(word)) is not None and section.address is None:
            section.address = address
        else:
            return None
    for word in after.split():
        subalign = inside(word, 'SUBALIGN(', ')')
        if subalign is not None and subalign.isdigit():
            section.subalign = int(subalign)
        elif inside(word, 'AT(', ')') is None:
            return None
    return section


def parse_placement(line):
    """Read `path/to/file.o(.section);`."""
    if not line.endswith(');'):
        return None
    path, _, section = line[:-len(');')].partition('(')
    if not path.endswith('.o') or ' ' in path or not section.startswith('.') or not is_name(section):
        return None
    return Placement(Path(path), section)


def parse_alignment(line):
    """Read `. = ALIGN(., 16);`."""
    boundary = inside(line, '. = ALIGN(., ', ');')
    return Alignment(int(boundary)) if boundary and boundary.isdigit() else None


def parse_padding(line):
    """Read `. += 0x40;`."""
    size = inside(line, '. += ', ';')
    if size and size.isdigit():
        return Padding(int(size))
    if (number := hex_number(size)) is not None:
        return Padding(number)
    return None


def parse_gp(line):
    """Read `_gp = 0x...;`, the value the gp register points at. MWLDPS2 needs it for gp-relative code."""
    return hex_number(inside(line, '_gp = ', ';'))


def is_bookkeeping(line):
    """Whether the line is one of splat's bookkeeping lines, which I leave out."""
    if line.startswith(BOOKKEEPING_STARTS):
        return True
    name, equals, value = line.partition(' = ')
    if not equals or not name.isidentifier() or not value.endswith(';'):
        return False
    value = value[:-1]
    return value in BOOKKEEPING_VALUES or value.startswith(BOOKKEEPING_FUNCTIONS)


def parse_symbol_definition(line):
    """Whether the line is a plain symbol address, like `func_00100AC0 = 0x100AC0;`."""
    name, equals, value = line.partition(' = ')
    return bool(equals) and ' ' not in name and hex_number(value[:-1]) is not None and value.endswith(';')


class ScriptReader:
    """Read splat's linker script one line at a time."""

    def __init__(self):
        self.sections = []
        self.gp = None
        self.current = None
        self.in_discard = False
        # An alignment line between two sections applies to the start of the
        # next one, so I hold on to it until that section begins.
        self.waiting_alignment = []

    def read(self, line, number):
        if line in STRUCTURE_LINES:
            return
        if line == DISCARD_BLOCK:
            self.in_discard = True
        elif line == BLOCK_END:
            self.current = None
            self.in_discard = False
        elif self.in_discard:
            require(line == DISCARD_EVERYTHING, f'line {number}: unexpected /DISCARD/ contents: {line}')
        elif not (self.read_gp(line) or self.read_between_sections(line) or self.read_inside_section(line)
                  or is_bookkeeping(line)):
            raise ValueError(f'line {number}: no MWLDPS2 equivalent for: {line}')

    def read_gp(self, line):
        gp = parse_gp(line)
        if gp is not None:
            self.gp = gp
        return gp is not None

    def read_between_sections(self, line):
        """A new section, or an alignment line waiting for one."""
        if self.current is not None:
            return False
        if section := parse_section_header(line):
            section.contents = [Alignment(boundary) for boundary in self.waiting_alignment]
            self.waiting_alignment = []
            self.sections.append(section)
            self.current = section
            return True
        if alignment := parse_alignment(line):
            self.waiting_alignment.append(alignment.boundary)
            return True
        return False

    def read_inside_section(self, line):
        """A placement, alignment, or padding line inside the current section."""
        if self.current is None:
            return False
        item = parse_placement(line) or parse_alignment(line) or parse_padding(line)
        if item:
            self.current.contents.append(item)
        return bool(item)


def parse_linker_script(text):
    """Read splat's linker script. Returns its sections in order and the gp value."""
    reader = ScriptReader()
    for number, line in enumerate(text.splitlines(), 1):
        reader.read(line.strip(), number)
    return reader.sections, reader.gp


def symbol_definitions(paths):
    """Read the `name = 0x...;` lines of the symbol scripts, from splat and linker_symbols.py."""
    lines = []
    for path in paths:
        for number, raw in enumerate(Path(path).read_text().splitlines(), 1):
            line = raw.strip()
            if not line:
                continue
            require(parse_symbol_definition(line), f'{path}:{number}: not a plain symbol address: {line}')
            lines.append(line)
    return lines


def check_unique_file_names(sections):
    """Make sure no two objects share a file name, since that's all MWLDPS2 goes by."""
    paths = {item.path for section in sections for item in section.contents if isinstance(item, Placement)}
    names = Counter(path.name for path in paths)
    duplicates = sorted(name for name, count in names.items() if count > 1)
    require(not duplicates, f"objects share a file name, which MWLDPS2 can't tell apart: {', '.join(duplicates)}")


def object_names(sections):
    """Every object's file name, in the order they're first placed."""
    names = [item.path.name for section in sections for item in section.contents if isinstance(item, Placement)]
    return list(dict.fromkeys(names))


def section_block(sections):
    """The lines for a run of splat's sections inside one output section."""
    lines = []
    for section in sections:
        lines.append(f'{INDENT}# {section.name}')
        lines += [INDENT + command for command in section.commands()]
    return lines


def command_file(sections, gp, symbols):
    """Write the whole command file: the module's region with every section in splat's order, then the rest.

    Sections before the first fixed address go in their own region at 0 first.
    Everything else in the module goes into a single output section. When I tried
    one output section per splat section, MWLDPS2 3.0 wrote a broken program
    header (the block came out 0x40 bytes too long, with a garbled memory size),
    even for cmc. The section names don't end up in the image anyway, so I keep
    them as comments to make the file easier to read.
    """
    check_unique_file_names(sections)
    file_start = list(takewhile(lambda section: section.address is None, sections))
    module = sections[len(file_start):]
    require(module, 'at least one section needs a fixed address')
    lines = [HEADER_COMMENT, 'MEMORY {']
    if file_start:
        lines.append(f'    {FILE_START_REGION} (RWX) : ORIGIN = 0x0, LENGTH = 0')
    lines += [
        f'    {MEMORY_REGION} (RWX) : ORIGIN = 0x{module[0].address:X}, LENGTH = 0',
        f'    {ELSEWHERE_REGION} (RWX) : ORIGIN = 0x{ELSEWHERE_ADDRESS:X}, LENGTH = 0',
        '}',
        'SECTIONS {',
    ]
    if file_start:
        lines.append(f'    {FILE_START_OUTPUT_SECTION} : {{')
        lines += section_block(file_start)
        lines.append(f'    }} > {FILE_START_REGION}')
    lines += [f'    {OUTPUT_SECTION} : {{', f'{INDENT}{ENTRY_SYMBOL} = .;']
    lines += section_block(module)
    if gp is not None:
        lines.append(f'{INDENT}_gp = 0x{gp:X};')
    lines += [INDENT + symbol for symbol in symbols]
    lines += [f'    }} > {MEMORY_REGION}', f'    {ELSEWHERE_OUTPUT_SECTION} : {{']
    # Asking for a section an object doesn't have is fine, so every object gets both.
    lines += [f'{INDENT}{name} ({section})' for name in object_names(sections) for section in EXCEPTION_SECTIONS]
    lines += [f'    }} > {ELSEWHERE_REGION}', '}']
    return '\n'.join(lines) + '\n'


def mwldps2_modules():
    """The names of the modules that link with MWLDPS2."""
    return set(json.loads(LINKER_CONFIG.read_text())['mwldps2_modules'])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('linker_script', type=Path, help="splat's linker script for the module")
    parser.add_argument('symbols', nargs='*', type=Path, help='symbol scripts to copy in')
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    sections, gp = parse_linker_script(args.linker_script.read_text())
    content = command_file(sections, gp, symbol_definitions(args.symbols))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content)


if __name__ == '__main__':
    main()
