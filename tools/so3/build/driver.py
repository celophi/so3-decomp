#!/usr/bin/env python3
"""Generate and run the boot/overlay build, including C, C++, and assembly units."""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

from tools.so3.build.boot import ROOT, original_boot
from tools.so3.build.compiler_probe import CONFIG, setup
from tools.so3.build.overlays import CONFIGS, load_config
from tools.so3.formats import require
from tools.so3.build.sdk import MANIFEST as SDK_MANIFEST, validate_sdk_units

BUILD_FILE = Path('build/build.ninja')
ASM_INCLUDE = re.compile(r'INCLUDE_(?:ASM|RODATA)\("([^"\n]+)",\s*([\w.$]+)\)')


def asm_inputs(source):
    if not source.exists():
        return []
    return [Path(folder) / (name + '.s') for folder, name in ASM_INCLUDE.findall(source.read_text())]


def pieces(config):
    options = config['options']
    result = []
    for segment in config['segments'][:-1]:
        if isinstance(segment, list):
            require(len(segment) == 3 and segment[1] == 'bin', 'expected a bin segment')
            result.append((Path(options['asset_path']) / (segment[2] + '.bin'), 'binary_object'))
        elif segment['type'] == 'bin':
            result.append((Path(options['asset_path']) / (segment['name'] + '.bin'), 'binary_object'))
        else:
            require(segment['type'] == 'code', 'expected a code segment')
            for sub in segment['subsegments']:
                if sub[1] == 'pad':
                    continue  # zero fill emitted by the linker script; no object
                require(len(sub) == 3 and sub[1] in ('asm', 'c', 'cpp'),
                        'expected an asm/c/cpp subsegment')
                key, suffix, rule = (('asm_path', '.s', 'assemble') if sub[1] == 'asm'
                                     else ('src_path', '.' + sub[1], 'compile'))
                result.append((Path(options[key]) / (sub[2] + suffix), rule))
    return result


def full_asm_path(options, source):
    relative = source.relative_to(options["src_path"]).with_suffix(".s")
    return Path(options["asm_path"]) / relative


def configure(configs):
    sdk_sources = validate_sdk_units(configs)
    lines = ['# Generated by tools/so3/build/driver.py from config/*.yaml and config/overlays/*.yaml.',
             'ninja_required_version = 1.3', 'builddir = build',
             'binutils = mips-ps2-decompals-',
             'pool split_pool', '  depth = 2',
             'pool compile_pool', f'  depth = {min(os.cpu_count() or 2, 8)}',
             'rule split', '  command = $split_command',
             '  description = SPLIT $module', '  pool = split_pool', '  restat = 1',
             'rule compile', '  command = python -m tools.so3.build.compile $in $out --macros $macro',
             '  description = COMPILE $in', '  pool = compile_pool',
             'rule compile_progress',
             '  command = python -m tools.so3.build.compile $in $out --macros $macro --skip-asm',
             '  description = PROGRESS $in', '  pool = compile_pool',
             'rule assemble',
             '  command = ${binutils}as -EL -march=r5900 -mabi=eabi -no-pad-sections -I $include -o $out $in',
             '  description = AS $in',
             'rule binary_object',
             '  command = ${binutils}objcopy -I binary -O elf32-littlemips -B mips:5900 $in $out',
             '  description = BIN $in',
             'rule link',
             '  command = ${binutils}ld -EL -T $layout -T $functions -T $symbols -o $out',
             '  description = LD $out',
             'rule binary_image', '  command = ${binutils}objcopy -O binary $in $out',
             '  description = IMAGE $out',
             'rule verify', '  command = $verify_command', '  description = VERIFY $module', '']
    compiler_config = json.loads(CONFIG.read_text())
    record = next(r for r in compiler_config['candidates'] if r['id'] == compiler_config['working_candidate'])
    compiler_files = [f'build/compilers/{record["id"]}/{name}' for name in record['files']]
    # This older MWCC has no -gccdep. Conservatively rebuild C/C++ when any project
    # header changes, including headers included indirectly from another header.
    headers = sorted(str(p) for root in ('include', 'src') for p in Path(root).rglob('*')
                     if p.suffix in ('.h', '.hpp', '.inc'))
    all_split, all_verify, all_progress = [], [], []
    report_units, categories = [], []
    for path, config in configs:
        options = config['options']
        is_boot = path.name == 'boot.us.yaml'
        module = 'boot' if is_boot else path.stem
        out = Path(options['build_path'])
        layout = options['ld_script_path']
        funcs, syms = options['undefined_funcs_auto_path'], options['undefined_syms_auto_path']
        include = options['generated_asm_macros_directory']
        macro = f'{include}/macro.inc'
        units = pieces(config)
        categories.append({'id': module, 'name': 'Boot' if is_boot else module})
        outputs = [layout, funcs, syms, macro] + [str(p) for p, _ in units]
        outputs += [str(a) for p, rule in units if rule == 'compile' for a in asm_inputs(p)]
        outputs += [str(full_asm_path(options, p))
                    for p, rule in units if rule == 'compile']
        outputs = list(dict.fromkeys(outputs))
        deps = [str(path), 'tools/so3/build/driver.py', 'tools/so3/__init__.py', 'tools/so3/formats.py',
                'tools/so3/build/sdk.py', str(SDK_MANIFEST)]
        deps += options.get('symbol_addrs_path', []) + options.get('reloc_addrs_path', [])
        # compile.py orders deferred units' .text by the module's symbol map.
        symbol_maps = [p for p in [f'config/symbols/{module}_symbol_addrs.txt',
                                 f'config/thunks/{module}_thunk_addrs.txt']
                       if Path(p).is_file()] + ([] if is_boot else [str(path)])
        deps += ['tools/so3/build/boot.py', 'config/manifests/versions.json'] if is_boot else ['tools/so3/build/overlays.py']
        split_command = 'python -m tools.so3.build.boot split' if is_boot else f'python -m tools.so3.build.overlays run-splat --overlay {module}'
        lines += [f'build {" ".join(outputs)}: split {options["target_path"]} | {" ".join(deps)}',
                  f'  split_command = {split_command}', f'  module = {module}']
        objects = []
        for piece, rule in units:
            obj = str(out / piece) + '.o' if rule == 'compile' else str(piece) + '.o'
            objects.append(obj)
            implicit = []
            if rule in ('assemble', 'compile'):
                implicit.append(macro)
            if rule == 'compile':
                implicit += [str(p) for p in asm_inputs(piece)] + headers + compiler_files
                implicit += ['tools/so3/build/compile.py', 'tools/so3/build/compiler_probe.py',
                             'tools/so3/build/text_order.py', *symbol_maps,
                             'tools/so3/__init__.py', 'config/manifests/compilers.json',
                             '/opt/mwccgap/mwccgap/mwccgap.py']
            lines += [f'build {obj}: {rule} {piece}' + (f' | {" ".join(implicit)}' if implicit else '')]
            if rule == 'assemble':
                lines += [f'  include = {include}']
            elif rule == 'compile':
                lines += [f'  macro = {macro}']
            if str(piece) in sdk_sources:
                continue
            metadata = {'progress_categories': [module], 'complete': False}
            unit = {'name': f'{module}/{piece.stem}', 'target_path': obj, 'metadata': metadata}
            if rule == 'compile':
                full_asm = full_asm_path(options, piece)
                target = str(full_asm) + '.o'
                base = str(Path('build/progress') / piece) + '.o'
                lines += [f'build {target}: assemble {full_asm} | {macro}',
                          f'  include = {include}',
                          f'build {base}: compile_progress {piece} | {" ".join(implicit)}',
                          f'  macro = {macro}']
                unit.update(target_path=target, base_path=base)
                metadata.update(source_path=str(piece), complete=not asm_inputs(piece))
                all_progress.append(base)
            else:
                metadata['auto_generated'] = True
            report_units.append(unit)
            all_progress.append(unit['target_path'])
        rebuilt = out / ('SLUS_204.88' if is_boot else 'rebuilt.bin')
        verify_command = (f'python -m tools.so3.build.boot verify --output {rebuilt} --report {out}/verify.json'
                          if is_boot else f'python -m tools.so3.build.overlays verify --overlay {module}')
        lines += [f'build {out}/linked.elf: link {" ".join(objects)} | {layout} {funcs} {syms}',
                  f'  layout = {layout}', f'  functions = {funcs}', f'  symbols = {syms}',
                  f'build {rebuilt}: binary_image {out}/linked.elf',
                  f'build {out}/verify.json: verify {rebuilt} | {options["target_path"]} {" ".join(deps)}',
                  f'  verify_command = {verify_command}', f'  module = {module}', '']
        all_split.extend(outputs)
        all_verify.append(f'{out}/verify.json')
    lines += [f'build split: phony {" ".join(all_split)}',
              f'build all: phony {" ".join(all_verify)}',
              f'build objdiff-objects: phony {" ".join(all_progress)}', 'default all', '']
    content = '\n'.join(lines)
    BUILD_FILE.parent.mkdir(parents=True, exist_ok=True)
    if not BUILD_FILE.exists() or BUILD_FILE.read_text() != content:
        BUILD_FILE.write_text(content)
    objdiff = {
        '$schema': 'https://raw.githubusercontent.com/encounter/objdiff/v3.8.2/config.schema.json',
        'min_version': '3.8.2',
        # Objects are built explicitly with make objdiff-objects or make report.
        'build_target': False, 'build_base': False,
        'units': report_units, 'progress_categories': categories,
    }
    content = json.dumps(objdiff, indent=2) + '\n'
    output = Path('objdiff.json')
    if not output.exists() or output.read_text() != content:
        output.write_text(content)


def run(configs, command):
    if command != 'split':
        config = json.loads(CONFIG.read_text())
        setup(next(r for r in config['candidates'] if r['id'] == config['working_candidate']))
    configure(configs)
    subprocess.run(['ninja', '-f', str(BUILD_FILE), 'split'], check=True)
    # A first split creates C/C++ files. Read their INCLUDE_ASM paths into the build
    # graph so missing assembly is regenerated and edits trigger compilation.
    configure(configs)
    if command in ('build', 'report'):
        subprocess.run(['ninja', '-f', str(BUILD_FILE), 'all'], check=True)
    if command in ('objdiff-objects', 'report'):
        subprocess.run(['ninja', '-f', str(BUILD_FILE), 'objdiff-objects'], check=True)
    if command == 'report':
        # Replace only after success; an interrupted run must not publish a partial report.
        output = Path('build/progress/report.json')
        temporary = output.with_suffix('.json.tmp')
        subprocess.run(['objdiff-cli', 'report', 'generate', '-o', str(temporary)], check=True)
        temporary.replace(output)


def main():
    import yaml
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('split', 'build', 'objdiff-objects', 'report'))
    args = parser.parse_args()
    os.chdir(ROOT)
    try:
        original_boot()
        path = Path('config/boot.us.yaml')
        configs = [(path, yaml.safe_load(path.read_text()))]
        configs += [(p, load_config(p)[0]) for p in sorted(CONFIGS.glob('*.yaml'))]
        run(configs, args.command)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f'error: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
